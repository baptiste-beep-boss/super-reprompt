# -*- coding: utf-8 -*-
"""Compute the instruction tokens read per tier (characters / 3.7) and write dev/CHARGEMENT-PAR-PALIER.md.

Run:  py -3 dev/measure_loading.py [--check]
The standard tier reads, for each reference, the sections named on its "Sections by tier" line. Headings inside
code fences are ignored. --check exits 1 when a budget is exceeded.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SK = os.path.join(ROOT, "skills", "super-reprompt")
REFS = os.path.join(SK, "references")
DIV = 3.7
LIMITS = {"SKILL.md": 4500, "quick.md": 1900, "quick": 6200, "standard": 17000}
STD_ORDER = ["phases.md", "interview.md", "order-template.md", "verification.md", "capabilities.md", "models.md",
             "launch.md", "agents.md"]


def tok(n):
    return int(round(n / DIV))


def sections(text):
    """Return [(heading, char_count)] with a leading ('', n) for the text before the first level-2 heading."""
    out, cur, n, fence = [("", 0)], "", 0, False
    out = []
    head, buf = "", []
    for line in text.split("\n"):
        if line.startswith("```"):
            fence = not fence
        if not fence and line.startswith("## "):
            out.append((head, len("\n".join(buf))))
            head, buf = line[3:].strip(), [line]
        else:
            buf.append(line)
    out.append((head, len("\n".join(buf))))
    return out


def standard_chars(fname):
    text = open(os.path.join(REFS, fname), encoding="utf-8").read()
    secs = sections(text)
    m = re.search(r"^Sections by tier — standard: (.*?)\. Max:", text, re.M)
    if not m:
        raise SystemExit("no 'Sections by tier' line in %s" % fname)
    wanted = [w.strip() for w in m.group(1).split(" · ")]
    total = secs[0][1]
    detail = []
    for w in wanted:
        if w.startswith("the Class section"):
            size = max(n for h, n in secs if h.startswith("Class"))
            detail.append("one Class section (largest)")
        else:
            # a clause after ';' is a conditional addition, not a heading
            w = w.split(";")[0].strip()
            hits = [n for h, n in secs if h == w]
            if not hits:
                raise SystemExit("%s: section %r not found" % (fname, w))
            size = hits[0]
            detail.append(w)
        total += size
    return total, detail


def main():
    skill = len(open(os.path.join(SK, "SKILL.md"), encoding="utf-8").read())
    quick = len(open(os.path.join(REFS, "quick.md"), encoding="utf-8").read())
    rows_std, std_total = [], skill
    for f in STD_ORDER:
        c, d = standard_chars(f)
        std_total += c
        rows_std.append((f, c))
    full = {f: len(open(os.path.join(REFS, f), encoding="utf-8").read()) for f in STD_ORDER}
    max_total = skill + quick * 0 + sum(full.values())
    # research.md is read only when the research agent is offered, so it is outside the standard total and reported apart.
    research_std, _d = standard_chars("research.md")
    research_full = len(open(os.path.join(REFS, "research.md"), encoding="utf-8").read())
    res = {"SKILL.md": tok(skill), "quick.md": tok(quick), "quick": tok(skill + quick), "standard": tok(std_total),
           "standard+research": tok(std_total + research_std), "max": tok(max_total + research_full)}
    md = ["# Instruction tokens read per tier", "",
          "Generated by `dev/measure_loading.py` (characters / 3.7). Starting values, not measurements of the model's usage.", "",
          "| Tier | Files read | Tokens |", "|---|---|---|",
          "| quick | `SKILL.md` (%d) + `quick.md` (%d) | **%d** |" % (res["SKILL.md"], res["quick.md"], res["quick"]),
          "| standard (no agents) | `SKILL.md` + the listed sections of each reference | **%d** |" % res["standard"],
          "| standard + research agent offered | the above + the four listed sections of `research.md` | **%d** |" % res["standard+research"],
          "| max | `SKILL.md` + every reference in full (examples excluded) | **%d** |" % res["max"], "",
          "## Standard tier by file", "", "| File | Tokens read | Full file |", "|---|---|---|",
          "| `SKILL.md` | %d | %d |" % (tok(skill), tok(skill))]
    for f, c in rows_std:
        md.append("| `%s` | %d | %d |" % (f, tok(c), tok(full[f])))
    md.append("| `research.md` (only when the research agent is offered, outside the standard total) | %d | %d |"
              % (tok(research_std), tok(research_full)))
    md += ["", "## Limits", "",
           "| Item | Limit | Measured | OK |", "|---|---|---|---|"]
    ok = True
    for key, label in (("SKILL.md", "SKILL.md"), ("quick.md", "quick.md"), ("quick", "quick total"), ("standard", "standard total (no agents)")):
        good = res[key] <= LIMITS[key]
        ok = ok and good
        md.append("| %s | %d | %d | %s |" % (label, LIMITS[key], res[key], "yes" if good else "NO"))
    md += ["", "The standard tier reads each reference once, only the sections its `Sections by tier` line names; the Class section "
           "counted is the largest one. Agents add `agents.md` sections (Do you need agents, Delegation contract, Reporting back) "
           "only when the order includes agents.", ""]
    with open(os.path.join(ROOT, "dev", "CHARGEMENT-PAR-PALIER.md"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(md))
    print(res)
    if "--check" in sys.argv and not ok:
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
